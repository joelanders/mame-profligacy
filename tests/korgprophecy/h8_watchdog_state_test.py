"""ROM-free regression for H8 watchdog interval-timer flag semantics.

The H8/3003 manual specifies two independent rules: OVF clears only after
software reads it as one and then writes zero, while interval mode requests an
interrupt at every TCNT overflow. This test extracts the relevant production
methods into a small type-compatible C++ harness and checks both rules.

It also checks that TCNT never counts backwards. The H8 core can present an
update time a few cycles before the previous one, and one prescaler step back
with TCNT at zero used to wrap into a spurious overflow.

Finally it checks that a TCNT write in interval mode settles the lazy counter
first, so an overflow that is due but not yet delivered still requests its
interrupt, and that in watchdog mode the same write replaces TCNT without
settling, so it cannot reset the CPU from inside the write instruction.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile


class TestFailure(RuntimeError):
    pass


def extract_method(source: str, qualified_name: str) -> str:
    match = re.search(
        rf"(?m)^[^\n]*\b{re.escape(qualified_name)}\s*\([^\n]*\)\s*(?:const\s*)?\{{",
        source,
    )
    if not match:
        raise TestFailure(f"production method not found: {qualified_name}")
    start = match.start()
    opening = source.find("{", match.start(), match.end())
    depth = 0
    for index in range(opening, len(source)):
        if source[index] == "{":
            depth += 1
        elif source[index] == "}":
            depth -= 1
            if depth == 0:
                return source[start : index + 1]
    raise TestFailure(f"unterminated production method: {qualified_name}")


def extract_table(source: str, declaration: str) -> str:
    start = source.find(declaration)
    if start < 0:
        raise TestFailure(f"production table not found: {declaration}")
    end = source.find(";", start)
    if end < 0:
        raise TestFailure(f"unterminated production table: {declaration}")
    return source[start : end + 1]


def make_shim(watchdog_cpp: str) -> str:
    tables = "\n".join(
        extract_table(watchdog_cpp, declaration)
        for declaration in (
            "const int h8_watchdog_device::div_bh[8]",
            "const int h8_watchdog_device::div_s [8]",
        )
    )
    methods = "\n\n".join(
        extract_method(watchdog_cpp, name)
        for name in (
            "h8_watchdog_device::tcnt_update",
            "h8_watchdog_device::wd_r",
            "h8_watchdog_device::wd_w",
        )
    )
    return f"""// Generated by h8_watchdog_state_test.py.
#include <cstdint>
#include <cstdlib>
#include <cstdio>

using u8 = std::uint8_t;
using u16 = std::uint16_t;
using u64 = std::uint64_t;
using offs_t = std::uint32_t;

#define logerror(...) ((void)0)

class machine_stub
{{
public:
    class time_stub {{ public: const char *as_string() const {{ return "0"; }} }};
    bool side_effects_disabled() const {{ return false; }}
    time_stub time() const {{ return {{}}; }}
}};

class cpu_stub
{{
public:
    u64 cycles = 0;
    int updates = 0;
    int resets = 0;
    u64 total_cycles() const {{ return cycles; }}
    void internal_update() {{ updates++; }}
    void reset() {{ resets++; }}
}};

class intc_stub
{{
public:
    int requests = 0;
    int last_vector = -1;
    void internal_interrupt(int vector) {{ requests++; last_vector = vector; }}
}};

template <typename T> class device_ref
{{
public:
    explicit device_ref(T &device) : m_device(&device) {{}}
    T *operator->() {{ return m_device; }}
private:
    T *m_device;
}};

class h8_watchdog_device
{{
public:
    enum {{ B, H, S }};
    enum {{
        TCSR_CKS = 0x07, TCSR_NMI = 0x08, TCSR_TME = 0x20,
        TCSR_WT = 0x40, TCSR_OVF = 0x80
    }};

    h8_watchdog_device(cpu_stub &cpu, intc_stub &intc)
        : m_cpu(cpu), m_intc(intc) {{}}

    static const int div_bh[8];
    static const int div_s[8];
    device_ref<cpu_stub> m_cpu;
    device_ref<intc_stub> m_intc;
    int m_irq = 20;
    int m_type = H;
    u8 m_tcnt = 0;
    u8 m_tcsr = 0;
    u8 m_rst = 0;
    bool m_ovf_clear_armed = false;
    u64 m_tcnt_cycle_base = 0;
    machine_stub m_machine;

    machine_stub &machine() {{ return m_machine; }}
    void tcnt_update(u64 current_time = 0);
    u16 wd_r();
    void wd_w(offs_t offset, u16 data, u16 mem_mask = ~u16(0));
}};

{tables}

{methods}

static bool check(bool condition, const char *message)
{{
    if (!condition)
        std::fprintf(stderr, "FAIL: %s\\n", message);
    return condition;
}}

int main()
{{
    cpu_stub cpu;
    intc_stub intc;
    h8_watchdog_device timer(cpu, intc);
    bool ok = true;

    timer.wd_w(0, 0xa53c);
    timer.wd_w(0, 0x5aff);
    cpu.cycles = 256;
    timer.tcnt_update(cpu.cycles);
    ok &= check(intc.requests == 1, "first overflow did not request IRQ");
    ok &= check((timer.m_tcsr & 0x80) != 0, "first overflow did not set OVF");

    timer.wd_w(0, 0xa51c);
    ok &= check((timer.m_tcsr & 0x80) != 0,
                "write without prior OVF read incorrectly cleared OVF");
    timer.wd_w(0, 0xa53c);
    timer.wd_w(0, 0x5aff);
    cpu.cycles += 256;
    timer.tcnt_update(cpu.cycles);
    ok &= check(intc.requests == 2,
                "second overflow did not request IRQ while OVF remained set");
    ok &= check(intc.last_vector == 20, "wrong interval IRQ vector");

    (void)timer.wd_r();
    timer.wd_w(0, 0xa51c);
    ok &= check((timer.m_tcsr & 0x80) == 0,
                "read-one then write-zero did not clear OVF");

    // The CPU core can present a time a few cycles before the previous
    // update. One prescaler step back with TCNT at zero must not count.
    cpu_stub rearm_cpu;
    intc_stub rearm_intc;
    h8_watchdog_device rearm(rearm_cpu, rearm_intc);
    rearm_cpu.cycles = 0x1001;
    rearm.wd_w(0, 0xa53c);
    rearm.tcnt_update(0x0fff);
    ok &= check(rearm_intc.requests == 0,
                "update before the previous one requested an interval IRQ");
    ok &= check((rearm.m_tcsr & 0x80) == 0,
                "update before the previous one set OVF");
    ok &= check(rearm.m_tcnt == 0, "update before the previous one changed TCNT");

    // Counting then continues from the later time: 0x3d needs 195 more
    // prescaler steps, so the overflow lands at cycle 0xd300 and not before.
    rearm.wd_w(0, 0x5a3d);
    rearm.tcnt_update(0xd2ff);
    ok &= check(rearm_intc.requests == 0, "interval IRQ arrived a step early");
    rearm.tcnt_update(0xd300);
    ok &= check(rearm_intc.requests == 1,
                "overflow after an ignored update did not request IRQ");

    // TCNT counts lazily, so an overflow can be due without having been
    // delivered yet. A TCNT write at that point must settle the counter
    // first: the overflow at cycle 0x100 still happens, and the new count
    // starts from the write.
    cpu_stub late_cpu;
    intc_stub late_intc;
    h8_watchdog_device late(late_cpu, late_intc);
    late.wd_w(0, 0xa53c);
    late.wd_w(0, 0x5aff);
    late_cpu.cycles = 0x180;
    late.wd_w(0, 0x5a00);
    ok &= check(late_intc.requests == 1,
                "TCNT write dropped an overflow that was already due");
    ok &= check((late.m_tcsr & 0x80) != 0,
                "TCNT write dropped the OVF of an overflow that was already due");
    ok &= check(late.m_tcnt == 0, "TCNT write did not set TCNT");
    // The next overflow counts 0x100 steps from the write's step (1).
    late.tcnt_update(0x100ff);
    ok &= check(late_intc.requests == 1, "overflow after a TCNT write arrived early");
    late.tcnt_update(0x10100);
    ok &= check(late_intc.requests == 2,
                "overflow after a TCNT write did not request IRQ");

    // In watchdog mode the same write must not settle the counter: that
    // would reset the CPU from inside the write instruction. The write
    // replaces TCNT, so a kick racing the overflow is accepted, and the
    // watchdog then fires 0x100 steps after the write's step (1).
    cpu_stub kick_cpu;
    intc_stub kick_intc;
    h8_watchdog_device kick(kick_cpu, kick_intc);
    kick.wd_w(0, 0xa564);
    kick.wd_w(0, 0x5aff);
    kick_cpu.cycles = 0x180;
    kick.wd_w(0, 0x5a00);
    ok &= check(kick_cpu.resets == 0,
                "watchdog-mode TCNT write reset the CPU from inside the write");
    ok &= check(kick_intc.requests == 0,
                "watchdog-mode TCNT write requested an interval IRQ");
    ok &= check((kick.m_tcsr & 0x80) == 0, "watchdog-mode TCNT write set OVF");
    ok &= check(kick.m_tcnt == 0, "watchdog-mode TCNT write did not set TCNT");
    ok &= check(kick.m_tcnt_cycle_base == 0x180,
                "watchdog-mode TCNT write did not restart counting at the write");
    kick.tcnt_update(0x100ff);
    ok &= check(kick_cpu.resets == 0, "watchdog reset after a kick arrived early");
    kick.tcnt_update(0x10100);
    ok &= check(kick_cpu.resets == 1, "watchdog did not reset the CPU after a kick");
    ok &= check(kick_intc.requests == 0 && (kick.m_tcsr & 0x80) == 0,
                "watchdog-mode overflow raised OVF or an interval IRQ");

    if (ok)
        std::puts("PASS: H8 watchdog OVF clearing, repeated interval IRQs, monotonic counting, settled TCNT writes and watchdog-mode kicks");
    return ok ? 0 : 1;
}}
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--root", type=Path, default=Path(__file__).resolve().parents[2]
    )
    args = parser.parse_args()
    root = args.root.resolve()
    watchdog_cpp = (root / "src/devices/cpu/h8/h8_watchdog.cpp").read_text(
        encoding="utf-8"
    )
    compiler = shutil.which("c++") or shutil.which("clang++") or shutil.which("g++")
    if not compiler:
        raise TestFailure("no C++ compiler found")
    with tempfile.TemporaryDirectory(prefix="h8-watchdog-") as temp_name:
        temp = Path(temp_name)
        source = temp / "h8_watchdog_test.cpp"
        binary = temp / "h8_watchdog_test"
        source.write_text(make_shim(watchdog_cpp), encoding="utf-8")
        compile_result = subprocess.run(
            [compiler, "-std=c++17", "-Wall", "-Wextra", "-Werror",
             "-Wno-unused-parameter", str(source), "-o", str(binary)],
            cwd=root, check=False, text=True, capture_output=True,
        )
        if compile_result.returncode:
            raise TestFailure(compile_result.stdout + compile_result.stderr)
        run_result = subprocess.run(
            [str(binary)], cwd=root, check=False, text=True, capture_output=True
        )
        sys.stdout.write(run_result.stdout)
        sys.stderr.write(run_result.stderr)
        if run_result.returncode:
            raise TestFailure("watchdog executable regression failed")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except TestFailure as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        raise SystemExit(1)
